/**
 * Debug builds only: trust user-installed CAs (and keep cleartext for Metro), so a proxy such as
 * ProxyPin can decrypt the app's own HTTPS while we debug campus protocols. Release builds get no
 * network security config at all (system CAs only, no cleartext), so this never ships.
 *
 * Writes android/app/src/debug/res/xml/network_security_config.xml and points the debug
 * manifest at it. https://developer.android.com/privacy-and-security/security-config
 */
const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by config-plugins/with-debug-user-ca.js (debug builds only). -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

module.exports = function withDebugUserCa(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const debug = path.join(cfg.modRequest.platformProjectRoot, 'app/src/debug');
      const xmlDir = path.join(debug, 'res/xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'network_security_config.xml'), CONFIG);

      const manifest = path.join(debug, 'AndroidManifest.xml');
      let xml = fs.readFileSync(manifest, 'utf8');
      if (!xml.includes('android:networkSecurityConfig')) {
        xml = xml
          .replace('<application ', '<application android:networkSecurityConfig="@xml/network_security_config" ')
          .replace('tools:replace="android:usesCleartextTraffic"', 'tools:replace="android:usesCleartextTraffic,android:networkSecurityConfig"');
        fs.writeFileSync(manifest, xml);
      }
      return cfg;
    },
  ]);
};
