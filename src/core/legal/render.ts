/** Builds documents.generated.ts from docs/legal (used by scripts/legal.ts and its test). */
export async function renderLegal() {
  const read = (name: string) => Bun.file(new URL(`../../../docs/legal/${name}.md`, import.meta.url)).text();
  const docs = {
    terms: { en: await read('terms.en'), 'zh-Hans': await read('terms.zh') },
    privacy: { en: await read('privacy.en'), 'zh-Hans': await read('privacy.zh') },
  };
  return `// Generated by scripts/legal.ts from docs/legal/*.md. Don't edit by hand.\nexport const LEGAL_DOCUMENTS = ${JSON.stringify(docs, null, 2)} as const;\n`;
}
